"""Follow-up tables from results/fm/{judge,mos,proxy}/*.json -> results/fm/tables.md (the tables in RESULTS.md's follow-up).

  ../.venv/bin/python report_fm.py
Whisper CER/WER are corpus-level (total edits / total reference characters or words), as judge.py reports them.
CIs: bootstrap over clips (2,000 resamples, seed 1). Paired differences resample the same clips for both systems.
"""
import json, os
import numpy as np

ROOT = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(ROOT, "results", "fm")
B = 2000


def load(kind, name):
    p = os.path.join(R, kind, name + ".json")
    return json.load(open(p)) if os.path.exists(p) else None


def per_clip(name):
    j, m = load("judge", name), load("mos", name)
    if j is None:
        return None
    ids = [c["id"] for c in j["clips"]]
    ce = np.array([round(c["cer"] * max(1, len(c["ref"]))) for c in j["clips"]], float)
    cn = np.array([max(1, len(c["ref"])) for c in j["clips"]], float)
    we = np.array([round(c["wer"] * max(1, len(c["ref"].split()))) for c in j["clips"]], float)
    wn = np.array([max(1, len(c["ref"].split())) for c in j["clips"]], float)
    mos = None
    if m is not None:
        mm = {c["id"]: c["mos"] for c in m["clips"]}
        mos = np.array([mm[i] for i in ids], float)
    return dict(ids=ids, ce=ce, cn=cn, we=we, wn=wn, mos=mos, cer=j["cer"], wer=j["wer"])


def boot_ci(f, n, seed=1):
    r = np.random.default_rng(seed)
    v = [f(r.integers(0, n, n)) for _ in range(B)]
    return float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5))


def fmt_ci(ci, d=2):
    return f"[{ci[0]:+.{d}f}, {ci[1]:+.{d}f}]"


def table(rows, ref_names, out):
    data = {lab: per_clip(n) for lab, n in rows}
    data = {k: v for k, v in data.items() if v is not None}
    out.append("| system | Whisper CER % [95% CI] | WER % | UTMOS [95% CI] |" +
               "".join(f" CER − {r} (pts) | UTMOS − {r} |" for r in ref_names))
    out.append("|---|---|---|---|" + "---|---|" * len(ref_names))
    for lab, d in data.items():
        n = len(d["ids"])
        ci = boot_ci(lambda i: 100 * d["ce"][i].sum() / d["cn"][i].sum(), n)
        cells = [lab, f"{d['cer']:.2f} [{ci[0]:.2f}, {ci[1]:.2f}]", f"{d['wer']:.2f}"]
        if d["mos"] is not None:
            mci = boot_ci(lambda i: d["mos"][i].mean(), n)
            cells.append(f"{d['mos'].mean():.3f} [{mci[0]:.3f}, {mci[1]:.3f}]")
        else:
            cells.append("not measured")
        for r in ref_names:
            e = data.get(r)
            if e is None or e is d or e["ids"] != d["ids"]:
                cells += ["", ""]
                continue
            dc = 100 * (d["ce"].sum() - e["ce"].sum()) / d["cn"].sum()
            cci = boot_ci(lambda i: 100 * (d["ce"][i].sum() - e["ce"][i].sum()) / d["cn"][i].sum(), n)
            cells.append(f"{dc:+.2f} {fmt_ci(cci)}")
            if d["mos"] is not None and e["mos"] is not None:
                dm = d["mos"] - e["mos"]
                mci = boot_ci(lambda i: dm[i].mean(), n)
                cells.append(f"{dm.mean():+.3f} {fmt_ci(mci, 3)}")
            else:
                cells.append("")
        out.append("| " + " | ".join(cells) + " |")
    return data


def proxy_table(names, out):
    out.append("| system | 27's CTC proxy CER %: predicted mel | : vocoded wav re-analysed | DTW log-mel L1 | MCD-like dB | GV ratio | length ratio | gen ms (median) |")
    out.append("|---|---|---|---|---|---|---|---|")
    for lab, n in names:
        p = load("proxy", n)
        if p is None:
            continue
        out.append(f"| {lab} | {p['ctc_cer_mel']:.1f} | {p['ctc_cer_neural']:.1f} | {p['dtw_logmel_l1']:.3f} | {p['mcd_like_db']:.2f} | "
                   f"{p['gv_ratio']:.3f} | {p['len_ratio_geomean']:.3f} | {p['gen_ms_median']:.0f} |")


def main():
    cfg = json.load(open(os.path.join(R, "systems.json")))
    out = ["# Follow-up tables (generated by report_fm.py)", ""]
    for sec in cfg["sections"]:
        out += [f"## {sec['title']}", ""]
        if sec.get("note"):
            out += [sec["note"], ""]
        rows = [(s[0], s[1]) for s in sec["rows"]]
        if sec.get("kind") == "proxy":
            proxy_table(rows, out)
        else:
            table(rows, sec.get("refs", []), out)
        out.append("")
    open(os.path.join(R, "tables.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
