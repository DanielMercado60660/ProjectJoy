"""Static network inspection only. No simulator imports or trajectories."""
import numpy as np

NAMES = ('W1', 'b1', 'W2', 'b2', 'W3', 'b3')

def load(path='start.npz'):
    with np.load(path, allow_pickle=False) as z:
        return {k: z[k].copy() for k in NAMES}

def forward(d, x):
    h1 = np.tanh(np.asarray(x) @ d['W1'] + d['b1'])
    h2 = np.tanh(h1 @ d['W2'] + d['b2'])
    z = h2 @ d['W3'] + d['b3']
    return np.tanh(z), h1, h2, z

def jacobian(d, x):
    a, h1, h2, z = forward(d, x)
    return ((d['W1'] * (1-h1*h1)) @ d['W2'] * (1-h2*h2)) @ d['W3']

# Distances are authored examples, in meters. They are neither observations
# from a track nor generated by a ray caster. Right bends mirror left bends.
RAYS = {
    'straight': [6, 6.93, 10.46, 19.42, 57.4, 57.4, 19.42, 10.46, 6.93, 6],
    'left_gentle': [6, 6.8, 9.8, 15.5, 26, 50, 25, 11.5, 7.1, 6],
    'left_medium': [6, 6.7, 9.3, 13.4, 19, 29, 36, 13, 7.3, 6],
    'left_tight': [6, 6.5, 8.5, 11.3, 14.8, 20, 28, 18, 7.6, 6],
    'near_left': [10, 11.55, 17.43, 32.36, 60, 19.13, 6.47, 3.49, 2.31, 2],
    'aim_left': [6.09, 8.06, 14.2, 43.1, 60, 21.77, 12.78, 8.49, 6.39, 6.09],
}
for name in list(RAYS):
    if name.startswith('left_'):
        RAYS[name.replace('left_', 'right_')] = RAYS[name][::-1]
RAYS['near_right'] = RAYS['near_left'][::-1]
RAYS['aim_right'] = RAYS['aim_left'][::-1]

def obs(name, speed=20., prev_steer=0., prev_pedal=1.):
    return np.array(RAYS[name] + [2*speed, 60*prev_steer, 60*prev_pedal])/60

def main():
    d = load()
    np.set_printoptions(precision=4, suppress=True, linewidth=180)
    print('Parameters', sum(v.size for v in d.values()))
    print('b1', d['b1'], '\nb2', d['b2'], '\nb3', d['b3'])
    print('\nStatic output probes: name, speed, steer, pedal, pre-tanh logits')
    for name in RAYS:
        for v in (0, 12, 20, 28, 36):
            a, h1, h2, z = forward(d, obs(name, v))
            print(name, v, np.round(a, 4), np.round(z, 4))
    for name in ('straight', 'left_medium', 'left_tight', 'near_right'):
        x = obs(name, 25)
        a,h1,h2,z = forward(d,x)
        print('\n',name, 'Jacobian of logits, rows = input, cols = output:\n',jacobian(d,x))
        for out in range(2):
            contrib = h2*d['W3'][:,out]
            ids = np.argsort(-np.abs(contrib))[:12]
            print('output',out,'h2 terms (id, h2, W3, contribution)', [(int(i),round(float(h2[i]),3),round(float(d['W3'][i,out]),3),round(float(contrib[i]),3)) for i in ids])
        h1_effect = ((d['W2']*(1-h2*h2)) @ d['W3'])
        print('h1 local logit effects (before tanh), columns steer,pedal:\n', h1_effect*(1-h1*h1)[:,None])

if __name__ == '__main__':
    main()
